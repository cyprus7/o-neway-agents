"""Application-owned dependencies. Concrete storage, inference and data live outside."""
from typing import Any, Protocol, ContextManager

from ..models import IntentExtraction, Job, Session, TravelIntent, TripOption


class IntentModelPort(Protocol):
    async def extract(self, session: Session) -> tuple[IntentExtraction, TravelIntent, list[str]]: ...


class PlanningRepository(Protocol):
    def transaction(self) -> ContextManager[None]: ...
    def get_session(self, session_id: str) -> Session | None: ...
    def save_session(self, session: Session) -> None: ...
    def get_job(self, job_id: str) -> Job | None: ...
    def save_job(self, job: Job) -> None: ...
    def add_event(self, session_id: str, step: str, status: str, message: str, **details: Any) -> None: ...
    def increment(self, name: str, amount: float = 1) -> None: ...
    def save_preferences(self, session: Session) -> None: ...
    def record_first_recommendation(self, session_id: str, seconds: float) -> None: ...
    def apply_refresh(self, job: Job, options: list[TripOption], outcomes: list[dict[str, Any]]) -> bool: ...
